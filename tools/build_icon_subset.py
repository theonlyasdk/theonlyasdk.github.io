#!/usr/bin/env python3
"""Regenerate the Font Awesome subset used by the site.

Scans the repository (and the last build in `_site/` when present) for every
`fa-*` class actually referenced, keeps only those glyphs in the WOFF2 fonts,
and rewrites `assets/lib/fontawesome-free/css/subset.css`.

Run this after adding an icon class anywhere in the site:

    python tools/build_icon_subset.py

Requires: fonttools with brotli (`pip install fonttools brotli`).
"""

import pathlib
import re

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
FA = ROOT / "assets" / "lib" / "fontawesome-free"

# Utility classes that are not glyphs.
UTILITY = {
    "fw", "spin", "pulse", "solid", "regular", "brands", "classic", "ul", "li",
    "inverse", "border", "stack", "beat", "fade", "spin-pulse", "spin-reverse",
    "sr-only", "xs", "sm", "lg", "2xs", "1x", "2x", "3x", "4x", "5x", "6x", "7x",
    "8x", "9x", "10x", "pull-left", "pull-right", "rotate-90", "rotate-180",
    "rotate-270", "flip-horizontal", "flip-vertical", "flip-both", "stack-1x",
    "stack-2x", "layers", "layers-counter", "layers-text", "text",
}

# Classes that are only emitted by JavaScript or conditional Liquid branches.
EXTRA = {"circle-exclamation", "square-x-twitter"}


def parse_codepoints() -> dict[str, int]:
    css = (FA / "css" / "all.min.css").read_text(encoding="utf-8", errors="ignore")
    found: dict[str, int] = {}
    for match in re.finditer(r'([^{}]+)\{--fa:"\\([0-9a-fA-F]+)"', css):
        codepoint = int(match.group(2), 16)
        for selector in match.group(1).split(","):
            selector = selector.strip()
            if re.fullmatch(r"\.fa-[a-z0-9-]+", selector):
                found.setdefault(selector[4:], codepoint)
    return found


def used_icons() -> set[str]:
    used: set[str] = set()
    skip = {"_site", "vendor", "node_modules", ".git", "assets", ".jekyll-cache"}
    for path in ROOT.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in {
            ".html", ".md", ".js", ".liquid", ".yml", ".yaml", ".scss"
        }:
            continue
        if set(path.parts) & skip:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        used.update(re.findall(r"\bfa-([a-z0-9-]+)\b", text))

    site = ROOT / "_site"
    if site.exists():
        for path in site.rglob("*.html"):
            text = path.read_text(encoding="utf-8", errors="ignore")
            for attr in re.findall(r'class="([^"]*)"', text):
                if re.search(r"\bfa[srlbd]?\b", attr):
                    used.update(re.findall(r"\bfa-([a-z0-9-]+)\b", attr))
    return used


def css_referenced_icons(codepoints: dict[str, int]) -> set[str]:
    """Icons emitted by CSS `content: '\\fXXX'` rules rather than HTML classes.

    Chirpy renders its prompt icons (tip/info/warning/danger) and a few other
    decorations this way, so class scanning alone misses them.
    """
    by_codepoint = {codepoint: name for name, codepoint in codepoints.items()}
    found: set[str] = set()
    for path in (ROOT / "_sass").rglob("*.scss"):
        text = path.read_text(encoding="utf-8", errors="ignore")
        for match in re.finditer(r"'\\([0-9a-fA-F]{3,6})'", text):
            name = by_codepoint.get(int(match.group(1), 16))
            if name:
                found.add(name)
    return found


def subset_font(src: pathlib.Path, dst: pathlib.Path, unicodes: list[int]) -> None:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.drop_tables += ["DSIG"]
    font = subset.load_font(str(src), options)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    subset.save_font(font, str(dst), options)


def main() -> None:
    codepoints = parse_codepoints()
    icons = sorted(
        ((used_icons() | css_referenced_icons(codepoints)) - UTILITY | EXTRA)
        & codepoints.keys()
    )

    rules = "\n".join(
        f'.fa-{name}{{--fa:"\\{codepoints[name]:x}"}}' for name in icons
    )

    css = f"""/*! Font Awesome Free 6.7.1 - subset build
 * Generated by tools/build_icon_subset.py - only the icons this site uses.
 * Icons: CC BY 4.0, Fonts: SIL OFL 1.1, Code: MIT License.
 * https://fontawesome.com/license/free
 */
@font-face{{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(../webfonts/fa-solid-subset.woff2) format("woff2")}}
@font-face{{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:400;font-display:block;src:url(../webfonts/fa-regular-subset.woff2) format("woff2")}}
@font-face{{font-family:"Font Awesome 6 Brands";font-style:normal;font-weight:400;font-display:block;src:url(../webfonts/fa-brands-subset.woff2) format("woff2")}}
:root{{--fa-font-brands:normal 400 1em/1 "Font Awesome 6 Brands";--fa-font-regular:normal 400 1em/1 "Font Awesome 6 Free";--fa-font-solid:normal 900 1em/1 "Font Awesome 6 Free"}}
.fa{{font-family:var(--fa-style-family,"Font Awesome 6 Free");font-weight:var(--fa-style,900)}}
.fa,.fa-brands,.fa-regular,.fa-solid,.fab,.far,.fas{{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}}
.fa-brands:before,.fa-regular:before,.fa-solid:before,.fa:before,.fab:before,.far:before,.fas:before{{content:var(--fa)}}
.fas,.fa-solid{{font-family:"Font Awesome 6 Free";font-weight:900}}
.far,.fa-regular{{font-family:"Font Awesome 6 Free";font-weight:400}}
.fab,.fa-brands{{font-family:"Font Awesome 6 Brands";font-weight:400}}
.fa-fw{{text-align:center;width:1.25em}}
.fa-spin{{animation-name:fa-spin;animation-duration:var(--fa-animation-duration,2s);animation-iteration-count:var(--fa-animation-iteration-count,infinite);animation-timing-function:var(--fa-animation-timing,linear)}}
@keyframes fa-spin{{0%{{transform:rotate(0)}}100%{{transform:rotate(360deg)}}}}
{rules}
"""
    (FA / "css" / "subset.css").write_text(css, encoding="utf-8")

    unicodes = [codepoints[name] for name in icons]
    for weight, src_name, dst_name in [
        ("solid", "fa-solid-900.ttf", "fa-solid-subset.woff2"),
        ("regular", "fa-regular-400.ttf", "fa-regular-subset.woff2"),
        ("brands", "fa-brands-400.ttf", "fa-brands-subset.woff2"),
    ]:
        src = FA / "webfonts" / src_name
        dst = FA / "webfonts" / dst_name
        subset_font(src, dst, unicodes)
        print(f"{weight}: {len(unicodes)} codepoints -> {dst.stat().st_size} bytes")

    print(f"subset.css: {len(css)} bytes, {len(icons)} icons")


if __name__ == "__main__":
    main()
