/**
 * Toast - a stacked notification library for the site.
 *
 * This is a port of Base UI's Toast (https://base-ui.com/react/components/toast)
 * to plain JS, keeping its stacking model, data attributes, and CSS variables
 * so the behaviour matches the reference implementation.
 *
 * `_javascript/` is a Rollup source directory that is NOT copied into the built
 * site, so this lives in `assets/js/` (see `assets/js/logger.js`). It is loaded
 * as a plain non-module script and exposes a global `Toast` manager.
 *
 * API:
 *   Toast.show('Copied to clipboard')
 *   Toast.show({ title: 'Ring index', description: '1 site.' })
 *   Toast.success('Deployed')  /  .error()  /  .warning()  /  .info()
 *   Toast.loading('Uploading')
 *   Toast.promise(fetch(url), { loading, success, error })
 *   const id = Toast.add({ title: 'x' }); Toast.update(id, { title: 'y' })
 *   Toast.close(id)   Toast.closeAll()
 *
 * Declarative alternative - no JavaScript in the page:
 *   <button data-toast-title="Saved" data-toast-description="All good.">
 *
 * Options: title, description, type, duration (0 = sticky), action, id,
 *          priority ('low' | 'high').
 *
 * CSS lives in `_sass/components/_toast.scss` and owns all motion. This file
 * only sets the CSS variables the stylesheet reads.
 */

const DEFAULT_DURATION = 5000;
const DEFAULT_LIMIT = 3;
const SWIPE_THRESHOLD = 45; // Sonner's value
const EXIT_MS = 500; // matches the opacity transition in _toast.scss
const SPRITE = '/assets/icons/hugeicons.svg';
const SPRITE_TYPES = ['success', 'error', 'warning', 'info', 'loading'];

/* Status -> Hugeicons symbol id. Icons are vendored in assets/icons/hugeicons.svg
   (generated by tools/build_hugeicons_sprite.js) and injected once on first use,
   so there is no third-party CDN request at runtime. */
function ensureSprite() {
  if (document.getElementById('hugeicons-sprite')) return;
  fetch(SPRITE)
    .then((r) => (r.ok ? r.text() : ''))
    .then((text) => {
      if (!text) return;
      const holder = document.createElement('div');
      holder.id = 'hugeicons-sprite';
      holder.setAttribute('aria-hidden', 'true');
      holder.style.display = 'none';
      holder.innerHTML = text;
      document.body.appendChild(holder);
    })
    .catch(() => {
      /* Icons are decorative; a missing sprite must not break the toast. */
    });
}

let viewport = null;
let expanded = false;
let sequence = 0;
const toasts = new Map(); // id -> { root, content, timer, remaining, started, ... }

/* ---------------------------------------------------------------- viewport */

function getViewport() {
  if (viewport && viewport.isConnected) return viewport;
  viewport = document.createElement('div');
  viewport.className = 'toast-viewport';
  viewport.tabIndex = -1;
  viewport.setAttribute('role', 'region');
  viewport.setAttribute('aria-label', 'Notifications');
  document.body.appendChild(viewport);
  return viewport;
}

/* Newest first, matching Base UI's index 0 = frontmost. */
function ordered() {
  return Array.from(toasts.values())
    .filter((t) => t.root.isConnected && !t.leaving)
    .reverse();
}

function readVar(name, fallback) {
  const raw = getComputedStyle(getViewport()).getPropertyValue(name).trim();
  const n = parseFloat(raw);
  return Number.isFinite(n) ? n : fallback;
}

function naturalHeight(entry) {
  /* .toast-content is pinned to the toast's current height, so its own box is
     not the natural height. Measure the text block plus the content padding. */
  const cs = getComputedStyle(entry.content);
  const pad = parseFloat(cs.paddingTop) + parseFloat(cs.paddingBottom);
  return entry.text.offsetHeight + (Number.isFinite(pad) ? pad : 0);
}

/**
 * Recomputes every CSS variable the stylesheet depends on. This is the port of
 * Base UI's internal layout pass, which sets --toast-index, --toast-height,
 * --toast-frontmost-height and --toast-offset-y on every state change.
 */
function layout() {
  const list = ordered();
  const limit = readVar('--toast-limit', DEFAULT_LIMIT);

  list.forEach((entry, index) => {
    entry.root.style.setProperty('--toast-index', String(index));
    entry.root.style.setProperty('--toast-height', `${naturalHeight(entry)}px`);
    entry.root.toggleAttribute('data-expanded', expanded);
    entry.content.toggleAttribute('data-expanded', expanded);
    // Behind the frontmost: hide the content so only the top card is readable.
    entry.content.toggleAttribute('data-behind', index > 0);

    // Base UI keeps over-limit toasts mounted but inert and transparent.
    const limited = index >= limit;
    entry.root.toggleAttribute('data-limited', limited);
    entry.root.inert = limited;
  });

  // Frontmost height clamps the collapsed stack.
  if (list.length) {
    getViewport().style.setProperty(
      '--toast-frontmost-height',
      `${naturalHeight(list[0])}px`
    );
  }

  // Cumulative natural height of everything in front. The inter-toast spacing
  // is deliberately NOT added here: the stylesheet adds
  // `index * --toast-expanded-gap` to --toast-offset-y itself, so adding it
  // again would double the gap.
  let acc = 0;
  list.forEach((entry) => {
    entry.root.style.setProperty('--toast-offset-y', `${acc}px`);
    acc += naturalHeight(entry);
  });
}

function setExpanded(next) {
  if (expanded === next) return;
  expanded = next;
  layout();
  // Tying the countdown to the expanded flag keeps the two from drifting apart,
  // whichever code path (hover, focus, Escape, F6) triggered the change.
  if (expanded) pauseAll();
  else resumeAll();
}

/* ------------------------------------------------------------------ timers */

function startTimer(entry) {
  const duration = entry.duration;
  if (!duration) return;
  entry.remaining = duration;
  entry.started = Date.now();
  entry.timer = window.setTimeout(() => close(entry.id), duration);
}

/* Hovering the viewport pauses every countdown, matching Base UI, where the
   stack stays open while you are reading it. */
function pauseAll() {
  toasts.forEach((entry) => {
    if (!entry.duration) return;
    window.clearTimeout(entry.timer);
    entry.timer = null;
    entry.remaining = Math.max(0, entry.duration - (Date.now() - entry.started));
  });
}

function resumeAll() {
  toasts.forEach((entry) => {
    if (!entry.duration || entry.timer || entry.remaining <= 0) return;
    entry.started = Date.now();
    entry.timer = window.setTimeout(() => close(entry.id), entry.remaining);
  });
}

/* ---------------------------------------------------------------- lifecycle */

function buildContent(entry, options) {
  const { content } = entry;
  content.textContent = '';

  const type = options.type || 'default';
  if (SPRITE_TYPES.includes(type)) {
    ensureSprite();
    const icon = document.createElement('span');
    icon.className = 'toast-icon';
    icon.setAttribute('aria-hidden', 'true');
    const use = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    use.setAttribute('class', 'toast-icon-svg');
    const ref = document.createElementNS('http://www.w3.org/2000/svg', 'use');
    ref.setAttribute('href', `#hugeicons-${type}`);
    use.appendChild(ref);
    icon.appendChild(use);
    content.appendChild(icon);
  }

  const text = document.createElement('div');
  text.className = 'toast-text';
  entry.text = text;

  if (options.title) {
    const title = document.createElement('div');
    title.className = 'toast-title';
    title.textContent = options.title;
    text.appendChild(title);
  }

  if (options.description) {
    const desc = document.createElement('div');
    desc.className = 'toast-description';
    desc.textContent = options.description;
    text.appendChild(desc);
  }

  content.appendChild(text);

  if (options.action) {
    const action = document.createElement('button');
    action.type = 'button';
    action.className = 'toast-action';
    action.textContent = options.action.label;
    action.addEventListener('click', () => {
      if (typeof options.action.onClick === 'function') options.action.onClick();
      close(entry.id);
    });
    content.appendChild(action);
  }

  const closeBtn = document.createElement('button');
  closeBtn.type = 'button';
  closeBtn.className = 'toast-close';
  closeBtn.textContent = 'Dismiss';
  closeBtn.addEventListener('click', () => close(entry.id));
  content.appendChild(closeBtn);

  // Announce high-priority toasts assertively.
  if (options.priority === 'high') {
    entry.root.setAttribute('aria-live', 'assertive');
  } else {
    entry.root.setAttribute('aria-live', 'polite');
  }
}

function add(options) {
  const opts = typeof options === 'string' ? { title: options } : options || {};
  const id = opts.id || `toast-${++sequence}`;
  const vp = getViewport();

  // Upsert: an existing id updates in place rather than duplicating.
  if (toasts.has(id)) {
    return update(id, opts);
  }

  const root = document.createElement('div');
  root.className = 'toast-item';
  root.tabIndex = -1;
  root.dataset.id = id;
  root.dataset.type = opts.type || 'default';

  const content = document.createElement('div');
  content.className = 'toast-content';
  root.appendChild(content);

  const entry = {
    id,
    root,
    content,
    duration: typeof opts.duration === 'number' ? opts.duration : DEFAULT_DURATION,
    remaining: 0,
    started: 0,
    timer: null,
    leaving: false
  };

  buildContent(entry, opts);
  toasts.set(id, entry);
  vp.appendChild(root);

  // Starting style, then released so the transition runs. The reflow is forced
  // synchronously rather than in a rAF: rAF is throttled in background tabs,
  // which would strand the toast at translateY(150%) and never reveal it.
  root.setAttribute('data-starting-style', '');
  layout();
  void root.offsetHeight;
  root.removeAttribute('data-starting-style');

  startTimer(entry);
  return id;
}

function update(id, changes) {
  const entry = toasts.get(id);
  if (!entry) return id;
  const next = typeof changes === 'function' ? changes(entry) : changes;
  const opts = next || {};

  if (typeof opts.duration === 'number') entry.duration = opts.duration;
  if (opts.type) entry.root.dataset.type = opts.type;

  buildContent(entry, {
    title: opts.title,
    description: opts.description,
    type: opts.type || entry.root.dataset.type,
    action: opts.action,
    priority: opts.priority
  });

  window.clearTimeout(entry.timer);
  entry.timer = null;
  layout();
  startTimer(entry);
  return id;
}

function close(id) {
  const entry = id ? toasts.get(id) : ordered()[0];
  if (!entry || entry.leaving) return;
  entry.leaving = true;

  window.clearTimeout(entry.timer);
  entry.root.setAttribute('data-ending-style', '');
  toasts.delete(entry.id);

  // Reflow now, not after the exit transition. The closing toast has already
  // been dropped from the list, so the survivors re-index and glide to their
  // new offsets at the same moment this one animates out. Deferring layout()
  // until the removal timeout made them sit still, then jump 500ms later.
  layout();

  window.setTimeout(() => {
    if (entry.root.parentNode) entry.root.parentNode.removeChild(entry.root);
    layout();
  }, EXIT_MS);
}

function closeAll() {
  Array.from(toasts.keys()).forEach(close);
}

/* ---------------------------------------------------------- drag to dismiss */

/* Ported from Sonner (https://github.com/emilkowalski/sonner). The parts that
   matter for feel: the drag axis locks on the first meaningful movement, travel
   in a disallowed direction is dampened rather than blocked (so a fast flick can
   still clear the threshold), and release dismisses on distance OR velocity. */

const SWIPE_VELOCITY = 0.11;
/* Derived from the position, as Sonner does: bottom-right -> ['bottom', 'right']. */
const SWIPE_DIRECTIONS = ['down', 'right'];

let drag = null;

function getDampening(delta) {
  const factor = Math.abs(delta) / 20;
  return 1 / (1.5 + factor);
}

function onPointerDown(e) {
  const root = e.target.closest('.toast-item');
  if (!root || e.button === 2) return; // ignore right click
  if (e.target.closest('button, a, [data-base-ui-swipe-ignore]')) return;
  // Sonner bails when the user is selecting text, so a drag-select never fights.
  if (window.getSelection && String(window.getSelection()).length > 0) return;

  const entry = toasts.get(root.dataset.id);
  if (!entry || entry.leaving) return;
  if (entry.root.dataset.type === 'loading') return; // loading is not dismissible

  drag = {
    id: entry.id,
    x: e.clientX,
    y: e.clientY,
    time: Date.now(),
    axis: null,
    amountX: 0,
    amountY: 0
  };

  // Keep tracking even when the pointer leaves the toast mid-drag.
  try {
    root.setPointerCapture(e.pointerId);
  } catch (err) {
    /* capture is best-effort */
  }

  root.setAttribute('data-swiping', '');
  pauseAll();
}

function onPointerMove(e) {
  if (!drag) return;
  const entry = toasts.get(drag.id);
  if (!entry) return;

  const xDelta = e.clientX - drag.x;
  const yDelta = e.clientY - drag.y;

  // Lock the axis on the first real movement.
  if (!drag.axis && (Math.abs(xDelta) > 1 || Math.abs(yDelta) > 1)) {
    drag.axis = Math.abs(xDelta) > Math.abs(yDelta) ? 'x' : 'y';
  }

  let amountX = 0;
  let amountY = 0;

  if (drag.axis === 'y') {
    if (SWIPE_DIRECTIONS.includes('bottom') || SWIPE_DIRECTIONS.includes('top')) {
      if (
        (SWIPE_DIRECTIONS.includes('bottom') && yDelta > 0) ||
        (SWIPE_DIRECTIONS.includes('top') && yDelta < 0)
      ) {
        amountY = yDelta;
      } else {
        const dampened = yDelta * getDampening(yDelta);
        amountY = Math.abs(dampened) < Math.abs(yDelta) ? dampened : yDelta;
      }
    }
  } else if (drag.axis === 'x') {
    if (SWIPE_DIRECTIONS.includes('right') || SWIPE_DIRECTIONS.includes('left')) {
      if (
        (SWIPE_DIRECTIONS.includes('right') && xDelta > 0) ||
        (SWIPE_DIRECTIONS.includes('left') && xDelta < 0)
      ) {
        amountX = xDelta;
      } else {
        const dampened = xDelta * getDampening(xDelta);
        amountX = Math.abs(dampened) < Math.abs(xDelta) ? dampened : xDelta;
      }
    }
  }

  drag.amountX = amountX;
  drag.amountY = amountY;

  entry.root.style.setProperty('--toast-swipe-movement-x', `${amountX}px`);
  entry.root.style.setProperty('--toast-swipe-movement-y', `${amountY}px`);

  if (amountX || amountY) entry.root.setAttribute('data-swiped', '');
}

function onPointerUp() {
  if (!drag) return;
  const entry = toasts.get(drag.id);
  const { axis, amountX, amountY, time } = drag;
  drag = null;
  if (!entry || entry.leaving) return;

  const amount = axis === 'x' ? amountX : amountY;
  const timeTaken = Math.max(1, Date.now() - time);
  const velocity = Math.abs(amount) / timeTaken;
  const allowed =
    axis === 'x'
      ? SWIPE_DIRECTIONS.includes(amountX > 0 ? 'right' : 'left')
      : SWIPE_DIRECTIONS.includes(amountY > 0 ? 'down' : 'up');

  entry.root.removeAttribute('data-swiped');

  // Release the transition lock first, otherwise `transition: none` from
  // [data-swiping] would also suppress the exit animation.
  entry.root.removeAttribute('data-swiping');

  if (allowed && (Math.abs(amount) >= SWIPE_THRESHOLD || velocity > SWIPE_VELOCITY)) {
    const direction =
      axis === 'x' ? (amountX > 0 ? 'right' : 'left') : amountY > 0 ? 'down' : 'up';
    entry.root.setAttribute('data-swipe-direction', direction);
    close(entry.id);
  } else {
    // Snap back to the resting position.
    entry.root.style.setProperty('--toast-swipe-movement-x', '0px');
    entry.root.style.setProperty('--toast-swipe-movement-y', '0px');
  }

  resumeAll();
}

document.addEventListener('pointerdown', onPointerDown, { passive: true });
document.addEventListener('pointermove', onPointerMove, { passive: true });
document.addEventListener('pointerup', onPointerUp, { passive: true });
document.addEventListener('pointercancel', onPointerUp, { passive: true });
window.addEventListener('dragend', onPointerUp, { passive: true });

/* -------------------------------------------------------------- interaction */

/* Hover anywhere over the stack expands it; leaving collapses it.
 *
 * The viewport is a zero-height anchor, so `pointerenter` on it alone is not a
 * dependable trigger - hence a delegated `pointerover` that fires whenever the
 * pointer is actually over one of the cards. Collapsing uses a hit test against
 * the union of every toast's rect (plus a margin) rather than a single toast's
 * box, so crossing the gaps between cards in the expanded stack does not make
 * it flicker. */

let hovering = false;
let lastPointer = null;

function stackBounds() {
  const rects = Array.from(getViewport().querySelectorAll('.toast-item')).map((t) =>
    t.getBoundingClientRect()
  );
  if (!rects.length) return null;
  return {
    left: Math.min(...rects.map((r) => r.left)),
    right: Math.max(...rects.map((r) => r.right)),
    top: Math.min(...rects.map((r) => r.top)),
    bottom: Math.max(...rects.map((r) => r.bottom))
  };
}

function pointerOverStack() {
  if (!lastPointer) return false;
  const bounds = stackBounds();
  if (!bounds) return false;
  const raw = getComputedStyle(getViewport())
    .getPropertyValue('--toast-hit-strip')
    .trim();
  const pad = parseFloat(raw) || 16;
  return (
    lastPointer.x >= bounds.left - pad &&
    lastPointer.x <= bounds.right + pad &&
    lastPointer.y >= bounds.top - pad &&
    lastPointer.y <= bounds.bottom + pad
  );
}

document.addEventListener(
  'pointerover',
  (e) => {
    if (!e.target.closest('.toast-item')) return;
    hovering = true;
    setExpanded(true);
  },
  { passive: true }
);

window.addEventListener(
  'pointermove',
  (e) => {
    if (!toasts.size) return;
    lastPointer = { x: e.clientX, y: e.clientY };
    if (hovering && !pointerOverStack()) {
      hovering = false;
      setExpanded(false);
    }
  },
  { passive: true }
);

document.addEventListener('mouseleave', () => {
  hovering = false;
  lastPointer = null;
  setExpanded(false);
});

getViewport().addEventListener('focusin', () => setExpanded(true));
getViewport().addEventListener('focusout', (e) => {
  if (!getViewport().contains(e.relatedTarget)) setExpanded(false);
});

document.addEventListener('keydown', (e) => {
  if (e.key !== 'Escape') return;
  const list = ordered();
  if (list.length) {
    close(list[0].id);
    setExpanded(false);
  }
});

// F6 jumps focus into the toast viewport, per Base UI.
document.addEventListener('keydown', (e) => {
  if (e.key !== 'F6') return;
  const list = ordered();
  if (!list.length) return;
  e.preventDefault();
  setExpanded(true);
  list[0].root.focus();
});

let resizeFrame = 0;
window.addEventListener('resize', () => {
  if (!toasts.size) return;
  cancelAnimationFrame(resizeFrame);
  resizeFrame = requestAnimationFrame(layout);
});

/* -------------------------------------------------------------------- public */

window.Toast = {
  add,
  show: add,
  update,
  close,
  closeAll,
  dismissAll: closeAll,
  success: (title, description, extra) =>
    add({ title, description, type: 'success', ...extra }),
  error: (title, description, extra) =>
    add({ title, description, type: 'error', ...extra }),
  warning: (title, description, extra) =>
    add({ title, description, type: 'warning', ...extra }),
  info: (title, description, extra) =>
    add({ title, description, type: 'info', ...extra }),
  loading: (title, description, extra) =>
    add({ title, description, type: 'loading', ...extra }),

  /** One toast that walks loading -> success | error. */
  promise(promiseValue, options) {
    const opts = options || {};
    const id = add({
      title: resolveText(opts.loading, undefined),
      description: resolveText(opts.loading, undefined, true),
      type: 'loading',
      duration: 0
    });
    return promiseValue.then(
      (result) => {
        update(id, {
          title: resolveText(opts.success, result),
          description: resolveText(opts.success, result, true),
          type: 'success'
        });
        return result;
      },
      (error) => {
        update(id, {
          title: resolveText(opts.error, error),
          description: resolveText(opts.error, error, true),
          type: 'error'
        });
        throw error;
      }
    );
  }
};

/* options may be a string or an object; `asDescription` picks description. */
function resolveText(option, arg, asDescription) {
  if (!option) return undefined;
  let value = option;
  if (typeof option === 'function') value = option(arg);
  else if (typeof option === 'object') {
    value = asDescription ? option.description : option.title;
  }
  return value === undefined ? undefined : String(value);
}

/* Declarative wiring: any element with data-toast-title becomes a trigger. */
document.addEventListener('click', (e) => {
  const trigger = e.target.closest('[data-toast-title]');
  if (!trigger) return;
  e.preventDefault();
  add({
    title: trigger.dataset.toastTitle,
    description: trigger.dataset.toastDescription,
    type: trigger.dataset.toastType,
    duration: Number(trigger.dataset.toastDuration) || undefined
  });
});
